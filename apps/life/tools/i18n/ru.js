// Типографика: неразрывный пробел перед длинным тире (« — » → «\u00a0— ») и после однобуквенных предлогов и союзов
// (в, с, к, и, а, о, у, я), чтобы тире не начинало строку, а «с» или «и» не висели в конце строки — и в HTML, и на холсте.
function typo(v) {
  if (typeof v === 'string') return v.replace(/ —/g, '\u00a0—').replace(/(^|[\s\u00a0«(])([ВСКИАОУЯвскиаоуя]) /g, '$1$2\u00a0');
  if (Array.isArray(v)) return v.map(typo);
  if (v && typeof v === 'object') { const o = {}; Object.keys(v).forEach((k) => { o[k] = typo(v[k]); }); return o; }
  return v;
}

